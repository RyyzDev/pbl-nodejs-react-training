let a = 30;
console.log("Nilai Awal: " + a)

/*
    Operator Assignment
*/

// Tambah lalu simpan
a += 10
console.log("Hasil tambah 10 lalu simpan: " + a);
// Kurang lalu simpan
a -= 10
console.log("Hasil kurang 10 lalu simpan: " + a);
// Kali lalu simpan
a *= 10
console.log("Hasil kali 10 lalu simpan: " + a);
// Bagi lalu simpan
a /= 10
console.log("Hasil bagi 10 lalu simpan: " + a);
// Modulus lalu simpan
a %= 9
console.log("Hasil modulus 9 lalu simpan: " + a);
// Increment (tambah 1)
a++;
console.log("Hasil Increment (tambah 1): " + a);
// Decrement (kurang 1)
a--;
console.log("Hasil Decrement (kurang 1): " + a);
